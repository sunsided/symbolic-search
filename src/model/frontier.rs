//! One direction of a cost-aware symbolic search: open buckets keyed by
//! `g` and `h`, and closed layers in expansion order.
//!
//! The same frontier runs symbolic Dijkstra (blind heuristic), `BDDA*` and
//! symbolic GBFS, forward or backward, in the concrete or a projected space.
//!
//! **Open.** New states at cost `g` are split by the heuristic partition and
//! filed under a [`Key`]: `(g + h, larger g first)` for the cost-optimal
//! [`Strategy::Cheapest`], `(h, smaller g first)` for [`Strategy::Greedy`].
//! Dead ends (outside the partition) are dropped.
//!
//! **Closed.** Each expanded set becomes an entry `(g, states)`. Popping
//! removes states already closed at a cost `≤ g` (any cost for greedy), so a
//! state is reopened only when it is found more cheaply. That keeps `BDDA*`
//! optimal with an admissible but inconsistent heuristic, and zero-cost
//! steps cannot loop.
//!
//! **Reconstruction invariant.** A state filed at cost `g` was either the
//! start at `g = 0`, or generated by a transition of cost `c` from a closed
//! entry with cost `g − c`. Entries are appended in expansion order, so the
//! generating entry always comes before any later entry of that state.
//! `Model::trace` relies on this.

use std::collections::BTreeMap;

use crate::backend::{Backend, BackendResult};
use crate::model::Direction;
use crate::model::heuristic::Partition;
use crate::model::space::Space;

/// Which open bucket a frontier expands next.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum Strategy {
    /// Smallest `g + h`, ties to the larger `g`: Dijkstra and `BDDA*`.
    Cheapest,
    /// Smallest `h`, ties to the smaller `g`: greedy best-first search.
    Greedy,
}

/// The sort key of an open bucket. Smaller keys are expanded first.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
struct Key {
    /// `g + h` for [`Strategy::Cheapest`], `h` for [`Strategy::Greedy`].
    priority: u64,
    /// Tie breaker: `u64::MAX − g` (larger `g` first) or `g`.
    tie: u64,
    /// Cost of the states in the bucket.
    g: u64,
}

/// One direction of a cost-aware symbolic search.
pub(crate) struct Frontier<'a, B: Backend> {
    /// The manager that owns every set.
    b: &'a B,
    /// The space searched.
    space: &'a Space<B>,
    /// Whether this frontier steps with images or preimages.
    direction: Direction,
    /// How the next bucket is chosen.
    strategy: Strategy,
    /// The heuristic that files new states into buckets.
    heuristic: Partition<B>,
    /// Open buckets. Sets may contain states that are already closed.
    open: BTreeMap<Key, B::Set>,
    /// Closed layers `(g, states)` in expansion order.
    entries: Vec<(u64, B::Set)>,
    /// Union of the closed layers per `g`.
    closed: BTreeMap<u64, B::Set>,
}

impl<'a, B: Backend> Frontier<'a, B> {
    /// A frontier that starts from `space.start(direction)` at cost 0.
    ///
    /// # Errors
    ///
    /// Out of memory in the backend.
    pub(crate) fn new(
        b: &'a B,
        space: &'a Space<B>,
        direction: Direction,
        heuristic: Partition<B>,
        strategy: Strategy,
    ) -> BackendResult<Self> {
        let mut frontier = Self {
            b,
            space,
            direction,
            strategy,
            heuristic,
            open: BTreeMap::new(),
            entries: Vec::new(),
            closed: BTreeMap::new(),
        };
        frontier.insert(0, space.start(direction))?;

        Ok(frontier)
    }

    /// The direction this frontier steps in.
    pub(crate) fn direction(&self) -> Direction {
        self.direction
    }

    /// The start set at cost 0.
    pub(crate) fn start(&self) -> &B::Set {
        self.space.start(self.direction)
    }

    /// Closed layers `(g, states)` in expansion order.
    pub(crate) fn entries(&self) -> &[(u64, B::Set)] {
        &self.entries
    }

    /// Union of the closed layers per `g`, ascending.
    pub(crate) fn closed(&self) -> &BTreeMap<u64, B::Set> {
        &self.closed
    }

    /// Whether no open bucket is left.
    pub(crate) fn is_exhausted(&self) -> bool {
        self.open.is_empty()
    }

    /// The smallest priority in open: a lower bound on `g + h` of every open
    /// state under [`Strategy::Cheapest`].
    pub(crate) fn min_priority(&self) -> Option<u64> {
        self.open.first_key_value().map(|(key, _)| key.priority)
    }

    /// The smallest `g` in open.
    pub(crate) fn min_g(&self) -> Option<u64> {
        self.open.keys().map(|key| key.g).min()
    }

    /// Node count of the bucket that is expanded next, 0 when open is empty.
    pub(crate) fn next_size(&self) -> usize {
        self.open
            .first_key_value()
            .map_or(0, |(_, set)| self.b.node_count(set))
    }

    /// Replaces the heuristic and refiles every open bucket under it.
    ///
    /// # Errors
    ///
    /// Out of memory in the backend.
    pub(crate) fn set_heuristic(&mut self, heuristic: Partition<B>) -> BackendResult<()> {
        self.heuristic = heuristic;
        for (key, set) in core::mem::take(&mut self.open) {
            self.insert(key.g, &set)?;
        }

        Ok(())
    }

    /// The current heuristic.
    pub(crate) fn heuristic(&self) -> &Partition<B> {
        &self.heuristic
    }

    /// Files `states` at cost `g` into the open buckets, split by `h`.
    ///
    /// # Errors
    ///
    /// Out of memory in the backend.
    fn insert(&mut self, g: u64, states: &B::Set) -> BackendResult<()> {
        let b = self.b;
        for (h, part) in self.heuristic.buckets() {
            let filed = b.and(states, part)?;
            if b.is_empty(&filed) {
                continue;
            }

            let key = self.key(g, *h);
            let merged = match self.open.get(&key) {
                Some(old) => b.or(old, &filed)?,
                None => filed,
            };
            self.open.insert(key, merged);
        }

        Ok(())
    }

    /// The open key of states with cost `g` and heuristic value `h`.
    fn key(&self, g: u64, h: u64) -> Key {
        match self.strategy {
            Strategy::Cheapest => Key {
                priority: g.saturating_add(h),
                tie: u64::MAX - g,
                g,
            },
            Strategy::Greedy => Key {
                priority: h,
                tie: g,
                g,
            },
        }
    }

    /// Removes the next bucket and returns its cost and the states in it that
    /// are not closed yet (see the module docs). Skips buckets that turn out
    /// empty. `None` when open is exhausted.
    ///
    /// # Errors
    ///
    /// Out of memory in the backend.
    pub(crate) fn pop(&mut self) -> BackendResult<Option<(u64, B::Set)>> {
        while let Some((key, set)) = self.open.pop_first() {
            let fresh = self.b.and(&set, &self.b.not(&self.closed_by(key.g)?)?)?;
            if !self.b.is_empty(&fresh) {
                return Ok(Some((key.g, fresh)));
            }
        }

        Ok(None)
    }

    /// The states that block a state found at cost `g`: closed at a cost
    /// `≤ g`, or closed at all for greedy search.
    ///
    /// # Errors
    ///
    /// Out of memory in the backend.
    fn closed_by(&self, g: u64) -> BackendResult<B::Set> {
        let mut range = match self.strategy {
            Strategy::Cheapest => self.closed.range(..=g),
            Strategy::Greedy => self.closed.range(..),
        };

        // shortcut: unions the closed layers per pop; cache a running union if profiles show it.
        range.try_fold(self.b.constant(false), |acc, (_, set)| self.b.or(&acc, set))
    }

    /// Closes `states` at cost `g`, then files their successors (or
    /// predecessors) at `g + c` for every relation group of cost `c`.
    /// Returns the generated `(cost, states)` pairs, for meeting checks.
    ///
    /// # Errors
    ///
    /// Out of memory in the backend.
    pub(crate) fn expand(&mut self, g: u64, states: &B::Set) -> BackendResult<Vec<(u64, B::Set)>> {
        self.close(g, states)?;

        let mut generated = Vec::new();
        for group in &self.space.groups {
            let next = group.step(self.b, states, self.direction)?;
            if self.b.is_empty(&next) {
                continue;
            }

            let cost = g.saturating_add(group.cost);
            self.insert(cost, &next)?;
            generated.push((cost, next));
        }

        Ok(generated)
    }

    /// Appends `states` as a closed entry at cost `g`.
    ///
    /// # Errors
    ///
    /// Out of memory in the backend.
    fn close(&mut self, g: u64, states: &B::Set) -> BackendResult<()> {
        self.entries.push((g, states.clone()));
        let merged = match self.closed.get(&g) {
            Some(old) => self.b.or(old, states)?,
            None => states.clone(),
        };
        self.closed.insert(g, merged);

        Ok(())
    }
}
